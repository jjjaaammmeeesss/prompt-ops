# === 组装完整提示词 ===

def build_analyzer_user_prompt(dialogue: str) -> str:
    """构建 Stage 1 分析器的用户消息。

    包含 few-shot 示例 + 待分析对话。
    """
    fewshot_blocks = []
    for i, example in enumerate(ZHOUYI_ANALYZER_FEWSHOTS, 1):
        output = example["output"]
        json_str = (
            "{"
            f'"下爻":"{output["下爻"]}",'
            f'"中爻":"{output["中爻"]}",'
            f'"上爻":"{output["上爻"]}",'
            f'"容器判定":"{output["容器判定"]}",'
            f'"风险":"{output["风险"]}",'
            f'"建议类型":"{output["建议类型"]}",'
            f'"一句话":"{output["一句话"]}",'
            f'"置信度":{output["置信度"]}'
            "}"
        )
        fewshot_blocks.append(
            f"### 示例{i}\n对话：\n{example['dialogue']}\n\n输出：\n{json_str}"
        )

    fewshot_text = "\n\n".join(fewshot_blocks)

    return f"""以下是几个校准示例，请仔细体会分析逻辑：

{fewshot_text}

---
## 待分析对话
{dialogue}

请输出JSON（只输出JSON，不要其他文字）："""


